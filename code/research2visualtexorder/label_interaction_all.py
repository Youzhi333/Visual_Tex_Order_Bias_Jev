"""2x2 label-permutation decomposition for every model and dataset.

    python research2visualtexorder/label_interaction_all.py

Option order is fixed. Label effect = identity vs permuted letters at the same
position. Position effect = suffix vs prefix under identity or permuted
letters. The interaction test asks whether the paired position-effect
indicators change under letter permutation. Writes
analysis_label_interaction_all.json and paper/tables/label_all.tex.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from scipy.stats import binomtest

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results" / "2026-11-12"
DATASET_NAMES = {
    "aokvqa": "A-OKVQA", "scienceqa": "ScienceQA", "cvbench": "CV-Bench",
    "eurosat": "EuroSAT", "pets": "Pets", "mmmu": "MMMU",
}
SHORT = {
    "Qwen3-VL-2B-Instruct": "Qwen3-VL-2B",
    "Qwen3-VL-4B-Instruct": "Qwen3-VL-4B",
    "Qwen3-VL-8B-Instruct": "Qwen3-VL-8B",
    "Qwen2.5-VL-7B-Instruct": "Qwen2.5-VL-7B",
    "Idefics3-8B-Llama3": "Idefics3-8B",
    "llava-onevision-qwen2-7b-ov-hf": "LLaVA-OneVision-7B",
    "llava-v1.6-mistral-7b-hf": "LLaVA-NeXT-7B",
}


def boot_ci(values, n_boot=4000, seed=0):
    values = np.asarray(values, dtype=float)
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, values.size, size=(n_boot, values.size))
    means = values[idx].mean(axis=1)
    return float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5))


def mcnemar(a, b):
    a = np.asarray(a, dtype=bool)
    b = np.asarray(b, dtype=bool)
    n01 = int(np.sum(~a & b))
    n10 = int(np.sum(a & ~b))
    if n01 + n10 == 0:
        return 1.0
    return float(binomtest(n01, n01 + n10, 0.5).pvalue)


def cell(label_path: Path) -> dict | None:
    label = json.loads(label_path.read_text(encoding="utf-8"))
    slug = label["model"].rstrip("/").split("/")[-1]
    raw_path = RESULTS / f"{slug}_{label['dataset']}_4pos.json"
    if not raw_path.exists():
        return None
    raw = json.loads(raw_path.read_text(encoding="utf-8"))
    names = raw["raw"]["metrics"]["positions"]
    truth = [it["answer"] for it in raw["items"]]
    n = min(label["n"], len(truth))
    id_pre = raw["raw"]["preds"][names[0]][:n]
    id_suf = raw["raw"]["preds"][names[-1]][:n]
    p_pre = label["positions"]["prefix"]["preds_permuted"][:n]
    p_suf = label["positions"]["suffix"]["preds_permuted"][:n]

    def flip(a, b):
        return np.asarray([x != y for x, y in zip(a, b)], dtype=float)

    pos_id = flip(id_suf, id_pre)
    pos_perm = flip(p_suf, p_pre)
    lab_pre = flip(p_pre, id_pre)
    lab_suf = flip(p_suf, id_suf)
    diff = pos_perm - pos_id
    return {
        "source": label_path.name,
        "model": label["model"],
        "dataset": label["dataset"],
        "n": n,
        "label_prefix": float(lab_pre.mean()),
        "label_suffix": float(lab_suf.mean()),
        "position_identity": float(pos_id.mean()),
        "position_permuted": float(pos_perm.mean()),
        "interaction": float(diff.mean()),
        "interaction_ci": boot_ci(diff),
        "interaction_p": mcnemar(pos_id, pos_perm),
        "position_permuted_ci": boot_ci(pos_perm),
    }


def main() -> int:
    rows = [r for r in (cell(p) for p in sorted(RESULTS.glob("label_perm_*.json"))
                    if not p.name.endswith("_full.json"))
            if r]
    rows.sort(key=lambda r: (list(SHORT).index(r["model"].rstrip("/").split("/")[-1])
                             if r["model"].rstrip("/").split("/")[-1] in SHORT else 99,
                             r["dataset"]))
    out = {"description": "letter permutation, option order fixed", "rows": rows}
    (RESULTS / "analysis_label_interaction_all.json").write_text(
        json.dumps(out, indent=2), encoding="utf-8")

    def group(label, test):
        g = [r for r in rows if test(r["model"])]
        if not g:
            return None
        return {
            "label": label, "cells": len(g),
            "label_prefix": float(np.mean([r["label_prefix"] for r in g])),
            "label_suffix": float(np.mean([r["label_suffix"] for r in g])),
            "position_identity": float(np.mean([r["position_identity"] for r in g])),
            "position_permuted": float(np.mean([r["position_permuted"] for r in g])),
            "interaction": float(np.mean([r["interaction"] for r in g])),
            "interaction_sig": int(sum(r["interaction_p"] < 0.05 for r in g)),
        }

    lines = [
        "% generated by label_interaction_all.py",
        "\\begin{tabular}{lrrrrr}",
        "\\toprule",
        "Model & cells & label pre/suf & position id & position perm & "
        "interaction $p<.05$ \\\\",
        "\\midrule",
    ]
    print(f"{'model':22s} {'cells':5s} {'label pre/suf':14s} "
          f"{'pos id':7s} {'pos perm':8s} {'inter sig'}")
    for slug, short in SHORT.items():
        g = [r for r in rows if r["model"].rstrip("/").split("/")[-1] == slug]
        if not g:
            continue
        s = group(short, lambda m, slug=slug: m.rstrip("/").split("/")[-1] == slug)
        lines.append(f"{short} & {s['cells']} & {s['label_prefix']:.3f}/"
                     f"{s['label_suffix']:.3f} & {s['position_identity']:.3f} & "
                     f"{s['position_permuted']:.3f} & "
                     f"{s['interaction_sig']}/{s['cells']} \\\\")
        print(f"{short:22s} {s['cells']:5d} "
              f"{s['label_prefix']:.3f}/{s['label_suffix']:.3f}      "
              f"{s['position_identity']:.3f}   {s['position_permuted']:.3f}    "
              f"{s['interaction_sig']}/{s['cells']}")
    for label, test in (("Qwen", lambda m: "Qwen" in m),
                        ("Non-Qwen", lambda m: "Qwen" not in m),
                        ("All", lambda m: True)):
        s = group(label, test)
        if s is None:
            continue
        lines.append(f"\\midrule\n{label} & {s['cells']} & "
                     f"{s['label_prefix']:.3f}/{s['label_suffix']:.3f} & "
                     f"{s['position_identity']:.3f} & {s['position_permuted']:.3f} & "
                     f"{s['interaction_sig']}/{s['cells']} \\\\")
        print(f"{label:22s} {s['cells']:5d} "
              f"{s['label_prefix']:.3f}/{s['label_suffix']:.3f}      "
              f"{s['position_identity']:.3f}   {s['position_permuted']:.3f}    "
              f"{s['interaction_sig']}/{s['cells']}")
    lines += ["\\bottomrule", "\\end{tabular}"]
    tex = ROOT / "paper/tables/label_all.tex"
    tex.parent.mkdir(parents=True, exist_ok=True)
    tex.write_text("\n".join(lines) + "\n", encoding="utf-8")
    cell_lines = [
        "% generated by label_interaction_all.py",
        "\\begin{tabular}{llrrrr}",
        "\\toprule",
        "Model & Dataset & $L_{pre}$ & $L_{suf}$ & $P_{id}$ & $P_{perm}$ \\\\",
        "\\midrule",
    ]
    for r in rows:
        cell_lines.append(
            f"{SHORT.get(r['model'].rstrip('/').split('/')[-1], r['model'])} & "
            f"{DATASET_NAMES.get(r['dataset'], r['dataset'])} & {r['label_prefix']:.3f} & {r['label_suffix']:.3f} & "
            f"{r['position_identity']:.3f} & {r['position_permuted']:.3f} \\\\")
    cell_lines += ["\\bottomrule", "\\end{tabular}"]
    cells_tex = ROOT / "paper/tables/label_cells.tex"
    cells_tex.write_text("\n".join(cell_lines) + "\n", encoding="utf-8")
    print(f"wrote {RESULTS / 'analysis_label_interaction_all.json'}\nwrote {tex}\n"
          f"wrote {cells_tex}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
