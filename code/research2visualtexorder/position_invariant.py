"""A placement-invariant reference for the modality-axis readout.

    python research2visualtexorder/position_invariant.py

For each model and dataset, average the per-item distributions over the four
image placements, then compare every placement to that average. This is an
image-position invariant reference, not an option-order average: the option
listing is fixed and no option rotation is performed.

Writes results/2026-11-12/analysis_position_invariant.json and prints a table.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results" / "2026-11-12"
POSITIONS = ("prefix", "middle", "question", "suffix")


def ece(conf, correct, bins=10):
    conf = np.asarray(conf, dtype=float)
    correct = np.asarray(correct, dtype=float)
    edges = np.linspace(0.0, 1.0, bins + 1)
    total = 0.0
    for i in range(bins):
        lo, hi = edges[i], edges[i + 1]
        mask = (conf >= lo) & (conf <= hi) if i == 0 else (conf > lo) & (conf <= hi)
        if mask.any():
            total += mask.mean() * abs(correct[mask].mean() - conf[mask].mean())
    return float(total)


def summarize(path: Path) -> dict:
    data = json.loads(path.read_text(encoding="utf-8"))
    raw = data["raw"]
    names = raw["metrics"]["positions"]
    if len(names) != len(POSITIONS):
        return {}
    items = data["items"]
    truth = np.asarray([it["answer"] for it in items])
    probs = np.stack([np.asarray(raw["probs"][name], dtype=float) for name in names], axis=1)
    p_bar = probs.mean(axis=1)
    inv_idx = p_bar.argmax(axis=1)
    inv_pred = [items[i]["options"][int(j)] for i, j in enumerate(inv_idx)]
    correct_inv = np.asarray([p == t for p, t in zip(inv_pred, truth)], dtype=float)
    per_position = {}
    for i, name in enumerate(names):
        pos_pred = raw["preds"][name]
        flips = np.asarray([a != b for a, b in zip(pos_pred, inv_pred)], dtype=float)
        tv = 0.5 * np.abs(probs[:, i] - p_bar).sum(axis=1).mean()
        per_position[POSITIONS[i]] = {
            "flip_vs_invariant": float(flips.mean()),
            "tv_vs_invariant": float(tv),
        }
    return {
        "source": path.name,
        "model": data["model"],
        "dataset": data["dataset"],
        "n": data["n"],
        "invariant_accuracy": float(correct_inv.mean()),
        "invariant_ece": ece(p_bar.max(axis=1), correct_inv),
        "per_position": per_position,
        "prefix_accuracy": raw["metrics"]["per_position"][names[0]]["accuracy"],
        "suffix_accuracy": raw["metrics"]["per_position"][names[-1]]["accuracy"],
        "suffix_flip_vs_prefix": raw["metrics"]["flip"][-1],
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--results", default=str(RESULTS))
    parser.add_argument("--out", default=str(RESULTS / "analysis_position_invariant.json"))
    args = parser.parse_args()
    files = sorted(Path(args.results).glob("*_4pos.json"))
    rows = [s for s in (summarize(p) for p in files) if s]
    if not rows:
        raise SystemExit("no _4pos files")
    payload = {"description": "average over the four image placements; option "
                             "listing fixed; no option rotation", "rows": rows}
    Path(args.out).write_text(json.dumps(payload, indent=2), encoding="utf-8")
    print(f"{'model':30s} {'data':9s} {'inv acc':8s} {'suf acc':8s} "
          f"{'flip pre':9s} {'flip suf':9s} {'suf flip vs pre':16s}")
    for r in rows:
        print(f"{r['model'].split('/')[-1]:30s} {r['dataset']:9s} "
              f"{r['invariant_accuracy']:8.3f} {r['suffix_accuracy']:8.3f} "
              f"{r['per_position']['prefix']['flip_vs_invariant']:9.3f} "
              f"{r['per_position']['suffix']['flip_vs_invariant']:9.3f} "
              f"{r['suffix_flip_vs_prefix']:16.3f}")
    mean = {
        key: float(np.mean([r[key] for r in rows]))
        for key in ("invariant_accuracy", "suffix_accuracy", "suffix_flip_vs_prefix")
    }
    mean["suffix_flip_vs_invariant"] = float(np.mean(
        [r["per_position"]["suffix"]["flip_vs_invariant"] for r in rows]))
    print(f"\nmean over {len(rows)} cells: invariant acc {mean['invariant_accuracy']:.3f}, "
          f"suffix acc {mean['suffix_accuracy']:.3f}, suffix flip vs prefix "
          f"{mean['suffix_flip_vs_prefix']:.3f}, vs invariant "
          f"{mean['suffix_flip_vs_invariant']:.3f}")
    lines = [
        "% generated by position_invariant.py; no option rotation",
        "\\begin{tabular}{lrrrr}",
        "\\toprule",
        "Family & cells & invariant acc & suffix acc & suffix flip "
        "(pre / inv) \\\\",
        "\\midrule",
    ]
    for label, test in (("All", lambda m: True),
                        ("Qwen", lambda m: "Qwen" in m),
                        ("Non-Qwen", lambda m: "Qwen" not in m)):
        group = [r for r in rows if test(r["model"])]
        inv = np.mean([r["invariant_accuracy"] for r in group])
        suf = np.mean([r["suffix_accuracy"] for r in group])
        pre = np.mean([r["suffix_flip_vs_prefix"] for r in group])
        invf = np.mean([r["per_position"]["suffix"]["flip_vs_invariant"] for r in group])
        lines.append(f"{label} & {len(group)} & {inv:.3f} & {suf:.3f} & "
                     f"{pre:.3f} / {invf:.3f} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    tex = Path(__file__).parent / "paper/tables/invariant.tex"
    tex.parent.mkdir(parents=True, exist_ok=True)
    tex.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.out}\nwrote {tex}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
