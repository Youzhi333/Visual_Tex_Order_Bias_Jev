"""Paired prefix/suffix statistics on the full evaluation sets.

    python research2visualtexorder/full_stats.py

Reads *_full.json only. Writes analysis_full_stats.json and a LaTeX table.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from scipy.stats import binomtest

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results" / "2026-11-12"


def boot_ci(values, n_boot=4000, seed=0):
    values = np.asarray(values, dtype=float)
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, values.size, size=(n_boot, values.size))
    means = values[idx].mean(axis=1)
    return float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5))


def mcnemar(a, b):
    a = np.asarray(a, dtype=bool)
    b = np.asarray(b, dtype=bool)
    n01, n10 = int(np.sum(~a & b)), int(np.sum(a & ~b))
    if n01 + n10 == 0:
        return 1.0
    return float(binomtest(n01, n01 + n10, 0.5).pvalue)


def main() -> int:
    rows = []
    for path in sorted(RESULTS.glob("*_full.json")):
        if "label_perm" in path.name or "analysis" in path.name:
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        names = data["raw"]["metrics"]["positions"]
        truth = [it["answer"] for it in data["items"]]
        pre = data["raw"]["preds"][names[0]]
        suf = data["raw"]["preds"][names[-1]]
        cpre = np.asarray([a == t for a, t in zip(pre, truth)], dtype=float)
        csuf = np.asarray([a == t for a, t in zip(suf, truth)], dtype=float)
        delta = csuf - cpre
        rows.append({
            "source": path.name, "model": data["model"], "dataset": data["dataset"],
            "n": data["n"], "accuracy_delta": float(delta.mean()),
            "delta_ci": boot_ci(delta), "mcnemar": mcnemar(cpre, csuf),
            "suffix_flip": float(np.mean([a != b for a, b in zip(suf, pre)])),
        })
    out = {"rows": rows}
    (RESULTS / "analysis_full_stats.json").write_text(json.dumps(out, indent=2),
                                                       encoding="utf-8")
    lines = [
        "% generated by full_stats.py from *_full.json",
        "\\begin{tabular}{lrrr}",
        "\\toprule",
        "Family & cells & mean $\\Delta$acc [95\\% CI] & McNemar $p<.05$ \\\\",
        "\\midrule",
    ]
    for label, test in (("Qwen", lambda m: "Qwen" in m),
                        ("Non-Qwen", lambda m: "Qwen" not in m),
                        ("All", lambda m: True)):
        group = [r for r in rows if test(r["model"])]
        if not group:
            continue
        deltas = np.asarray([r["accuracy_delta"] for r in group])
        lo, hi = boot_ci(deltas)
        sig = sum(r["mcnemar"] < 0.05 for r in group)
        lines.append(f"{label} & {len(group)} & {deltas.mean():+.3f} "
                     f"[{lo:+.3f}, {hi:+.3f}] & {sig}/{len(group)} \\\\")
        print(label, len(group), "delta", round(deltas.mean(), 3),
              "CI", (round(lo, 3), round(hi, 3)), "sig", f"{sig}/{len(group)}")
    lines += ["\\bottomrule", "\\end{tabular}"]
    tex = ROOT / "paper/tables/full_stats.tex"
    tex.parent.mkdir(parents=True, exist_ok=True)
    tex.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {RESULTS / 'analysis_full_stats.json'}\nwrote {tex}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
