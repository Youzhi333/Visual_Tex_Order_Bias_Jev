"""Write the non-Qwen six-dataset table from the result JSONs.

    python research2visualtexorder/make_nonqwen_table.py

One row per model and dataset: prefix accuracy, suffix accuracy, suffix flip.
The position names differ for the LLaVA splice runs, so positions are read by
order (prefix first, suffix last). Writes paper/tables/nonqwen_grid.tex.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results" / "2026-11-12"
TEX = ROOT / "paper" / "tables" / "nonqwen_grid.tex"
MODELS = (
    ("Idefics3-8B-Llama3", "Idefics3-8B"),
    ("llava-onevision-qwen2-7b-ov-hf", "LLaVA-OneVision-7B"),
    ("llava-v1.6-mistral-7b-hf", "LLaVA-NeXT-7B"),
)
DATASETS = (
    ("aokvqa", "A-OKVQA"),
    ("scienceqa", "ScienceQA"),
    ("cvbench", "CV-Bench"),
    ("eurosat", "EuroSAT"),
    ("pets", "Pets"),
    ("mmmu", "MMMU"),
)


def row(path: Path, label: str, dataset: str):
    data = json.loads(path.read_text(encoding="utf-8"))
    metrics = data["raw"]["metrics"]
    positions = metrics["positions"]
    prefix, suffix = positions[0], positions[-1]
    flip = metrics["flip"][-1]
    acc_p = metrics["per_position"][prefix]["accuracy"]
    acc_s = metrics["per_position"][suffix]["accuracy"]
    return (f"{label} & {dataset} & {acc_p:.3f} & {acc_s:.3f} & "
            f"{flip:.3f} \\\\")


def main() -> int:
    blocks = []
    for model, label in MODELS:
        rows = []
        for key, dataset in DATASETS:
            path = RESULTS / f"{model}_{key}_4pos.json"
            if path.exists():
                rows.append(row(path, label, dataset))
        if rows:
            blocks.append("\n".join(rows))
    if not blocks:
        raise SystemExit(f"no non-Qwen _4pos files under {RESULTS}")
    lines = [
        "% generated by make_nonqwen_table.py from *_4pos.json",
        "\\begin{tabular}{llrrr}",
        "\\toprule",
        "Model & Dataset & prefix & suffix & suffix flip \\\\",
        "\\midrule",
        "\n\\midrule\n".join(blocks),
        "\\bottomrule",
        "\\end{tabular}",
    ]
    TEX.parent.mkdir(parents=True, exist_ok=True)
    TEX.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {TEX} ({sum(b.count(chr(10)) + 1 for b in blocks)} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
