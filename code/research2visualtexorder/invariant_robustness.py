"""Robustness table for the placement-invariant reference.

    python research2visualtexorder/invariant_robustness.py

Compares three image-position references computed from the committed JSONs:
the four-slot average, the leave-one-out average, and the five token-position
average. No option rotation and no new model runs.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results" / "2026-11-12"


def boot_ci(values, n_boot=4000, seed=0):
    values = np.asarray(values, dtype=float)
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, values.size, size=(n_boot, values.size))
    means = values[idx].mean(axis=1)
    return float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5))


def main() -> int:
    full = json.loads((RESULTS / "analysis_position_invariant.json").read_text())["rows"]
    loo = json.loads((RESULTS / "analysis_position_invariant_loo.json").read_text())["rows"]
    token = json.loads((RESULTS / "analysis_token_invariant.json").read_text())["rows"]
    rows = []
    for label, test in (("Qwen", lambda m: "Qwen" in m),
                        ("Non-Qwen", lambda m: "Qwen" not in m),
                        ("All", lambda m: True)):
        f = [r["per_position"]["suffix"]["flip_vs_invariant"]
             for r in full if test(r["model"])]
        l = [r["per_position"]["suffix"]["flip"] for r in loo if test(r["model"])]
        t = [r["suffix_flip_vs_invariant"] for r in token if test(r["model"])]
        rows.append({
            "family": label, "cells": len(f),
            "full": float(np.mean(f)), "full_ci": boot_ci(f),
            "loo": float(np.mean(l)), "loo_ci": boot_ci(l),
            "token": float(np.mean(t)), "token_ci": boot_ci(t),
            "invariant_accuracy": float(np.mean(
                [r["invariant_accuracy"] for r in full if test(r["model"])])),
        })
    lines = [
        "% generated by invariant_robustness.py",
        "\\begin{tabular}{lrrrr}",
        "\\toprule",
        "Family & four-slot & leave-one-out & token-position & invariant acc \\\\",
        "\\midrule",
    ]
    for r in rows:
        lines.append(
            f"{r['family']} & {r['full']:.3f} [{r['full_ci'][0]:.3f},"
            f"{r['full_ci'][1]:.3f}] & {r['loo']:.3f} "
            f"[{r['loo_ci'][0]:.3f},{r['loo_ci'][1]:.3f}] & "
            f"{r['token']:.3f} [{r['token_ci'][0]:.3f},{r['token_ci'][1]:.3f}] & "
            f"{r['invariant_accuracy']:.3f} \\\\")
        print(r["family"], "full", round(r["full"], 3),
              "loo", round(r["loo"], 3), "token", round(r["token"], 3))
    lines += ["\\bottomrule", "\\end{tabular}"]
    tex = ROOT / "paper/tables/invariant_robustness.tex"
    tex.parent.mkdir(parents=True, exist_ok=True)
    tex.write_text("\n".join(lines) + "\n", encoding="utf-8")
    (RESULTS / "analysis_invariant_robustness.json").write_text(
        json.dumps({"rows": rows}, indent=2), encoding="utf-8")
    print(f"wrote {RESULTS / 'analysis_invariant_robustness.json'}\nwrote {tex}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
