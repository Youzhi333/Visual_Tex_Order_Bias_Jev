"""Readout tables aggregated by model and by dataset.

    python research2visualtexorder/make_aggregate_tables.py

Writes paper/tables/bymodel.tex and paper/tables/bydataset.tex from the
committed _4pos.json files. Each cell is "accuracy / flip (%)" relative to
prefix. Pointwise is omitted because it covers only A-OKVQA and EuroSAT; it is
reported in tab:fuse and tab:fusefull.
"""
from __future__ import annotations

from pathlib import Path

from readouts import READOUTS, cell

ROOT = Path(__file__).resolve().parent
TABLES = ROOT / "paper" / "tables"
MODELS = (
    ("Qwen", "2B", "Qwen3-VL-2B-Instruct"),
    ("Qwen", "4B", "Qwen3-VL-4B-Instruct"),
    ("Qwen", "8B", "Qwen3-VL-8B-Instruct"),
    ("Qwen", "Qwen2.5-7B", "Qwen2.5-VL-7B-Instruct"),
    ("Non-Qwen", "Idefics3", "Idefics3-8B-Llama3"),
    ("Non-Qwen", "LLaVA-OV", "llava-onevision-qwen2-7b-ov-hf"),
    ("Non-Qwen", "LLaVA-NeXT", "llava-v1.6-mistral-7b-hf"),
)
DATASETS = (("aokvqa", "A-OKVQA"), ("scienceqa", "ScienceQA"),
            ("cvbench", "CV-Bench"), ("eurosat", "EuroSAT"),
            ("pets", "Pets"), ("mmmu", "MMMU"))


def fmt(value: tuple[float, float, float]) -> str:
    return f"{value[0]:.3f} / {100 * value[1]:.1f}"


def mean(values: list[tuple[float, float, float]]) -> tuple[float, float, float]:
    n = len(values)
    return tuple(sum(v[i] for v in values) / n for i in range(3))  # type: ignore[return-value]


def main() -> int:
    cells = {(slug, ds): cell(slug, ds) for _, _, slug in MODELS for ds, _ in DATASETS}

    model_rows = []
    for _, short, slug in MODELS:
        vals = {key: mean([cells[(slug, ds)][key] for ds, _ in DATASETS])
                for _, key in READOUTS}
        model_rows.append((short, vals))

    ds_rows = {"All": [], "Qwen": [], "Non-Qwen": []}
    for group in ("All", "Qwen", "Non-Qwen"):
        members = [slug for g, _, slug in MODELS if group == "All" or g == group]
        for ds, label in DATASETS:
            vals = {key: mean([cells[(slug, ds)][key] for slug in members])
                    for _, key in READOUTS}
            ds_rows[group].append((label, vals))

    model = [
        "% generated by make_aggregate_tables.py",
        "\\begin{tabular}{lrrrrrrr}",
        "\\toprule",
        "Readout & " + " & ".join(m[1] for m in MODELS) + " \\\\",
        "\\midrule",
        *[f"{label} & " + " & ".join(fmt(row[1][key]) for row in model_rows) + " \\\\"
          for label, key in READOUTS],
        "\\bottomrule",
        "\\end{tabular}",
    ]
    dataset = [
        "% generated by make_aggregate_tables.py",
        "\\begin{tabular}{lrrrrrr}",
        "\\toprule",
        "Readout & " + " & ".join(d[1] for d in DATASETS) + " \\\\",
        "\\midrule",
    ]
    titles = {
        "All": "All-model mean over seven checkpoints",
        "Qwen": "Qwen mean over four checkpoints",
        "Non-Qwen": "Non-Qwen mean over three checkpoints",
    }
    for gi, group in enumerate(("All", "Qwen", "Non-Qwen")):
        if gi:
            dataset.append("\\midrule")
        dataset.append(f"\\multicolumn{{7}}{{l}}{{\\textit{{{titles[group]}}}}} \\\\")
        dataset.extend(
            f"{label} & " + " & ".join(fmt(row[1][key]) for row in ds_rows[group]) + " \\\\"
            for label, key in READOUTS)
    dataset.extend(["\\bottomrule", "\\end{tabular}"])

    TABLES.mkdir(parents=True, exist_ok=True)
    for name, lines in (("bymodel.tex", model), ("bydataset.tex", dataset)):
        (TABLES / name).write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"wrote {TABLES / name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
