"""Per-cell token-level r table.

    python research2visualtexorder/make_token_table.py

Writes paper/tables/token_table.tex from the *_token.json files. Columns are
prefix accuracy, flip at token r=0.25/0.5/0.75 and suffix, and accuracy at
token r=0.75 and suffix.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results" / "2026-11-12"
TABLES = ROOT / "paper" / "tables"
MODELS = (
    ("Qwen", "Qwen3-VL-2B-Instruct", "2B"),
    ("Qwen", "Qwen3-VL-4B-Instruct", "4B"),
    ("Qwen", "Qwen3-VL-8B-Instruct", "8B"),
    ("Qwen", "Qwen2.5-VL-7B-Instruct", "7B"),
    ("Non-Qwen", "Idefics3-8B-Llama3", "Idefics3-8B"),
    ("Non-Qwen", "llava-onevision-qwen2-7b-ov-hf", "LLaVA-OneVision"),
    ("Non-Qwen", "llava-v1.6-mistral-7b-hf", "LLaVA-NeXT"),
)
DATASETS = (("aokvqa", "A-OKVQA"), ("scienceqa", "ScienceQA"),
            ("cvbench", "CV-Bench"), ("eurosat", "EuroSAT"),
            ("pets", "Pets"), ("mmmu", "MMMU"))


def main() -> int:
    lines = [
        "% generated by make_token_table.py",
        "\\begin{tabular}{llrrrrrrr}",
        "\\toprule",
        "Model & Dataset & prefix & $F_{.25}$ & $F_{.5}$ & $F_{.75}$ & $F_{\\mathrm{suf}}$"
        " & acc$_{.75}$ & acc$_{\\mathrm{suf}}$ \\\\",
        "\\midrule",
    ]
    for gi, group in enumerate(("Qwen", "Non-Qwen")):
        if gi:
            lines.append("\\midrule")
        lines.append(f"\\multicolumn{{9}}{{l}}{{\\textit{{{group}}}}}\\\\")
        for g, slug, short in MODELS:
            if g != group:
                continue
            for ds, label in DATASETS:
                path = RESULTS / f"{slug}_{ds}_token.json"
                if not path.exists():
                    path = RESULTS / f"{slug}_{ds}_token6.json"
                data = json.loads(path.read_text(encoding="utf-8"))
                m = data["raw"]["metrics"]
                names = m["positions"]
                flip = m["flip"]
                acc = [m["per_position"][n]["accuracy"] for n in names]
                lines.append(
                    f"{short} & {label} & {acc[0]:.3f} & {flip[1]:.3f} & {flip[2]:.3f} & "
                    f"{flip[3]:.3f} & {flip[4]:.3f} & {acc[3]:.3f} & {acc[4]:.3f} \\\\")
    lines.extend(["\\bottomrule", "\\end{tabular}"])
    TABLES.mkdir(parents=True, exist_ok=True)
    (TABLES / "token_table.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {TABLES / 'token_table.tex'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
