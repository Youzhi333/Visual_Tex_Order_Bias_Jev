"""Grey-image control table.

    python research2visualtexorder/make_grey_table.py

Writes paper/tables/grey.tex: raw and grey prefix/suffix accuracy and suffix
flip for the Qwen3-VL-4B pilot and the three non-Qwen checkpoints on
A-OKVQA/EuroSAT.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results" / "2026-11-12"
TABLES = ROOT / "paper" / "tables"
QWEN = (
    ("Qwen3-VL-4B-Instruct", "4B",
     ("Qwen3-VL-4B-Instruct_aokvqa.json", "Qwen3-VL-4B-Instruct_eurosat.json")),
)
NONQWEN = (
    ("Idefics3-8B-Llama3", "Idefics3-8B"),
    ("llava-onevision-qwen2-7b-ov-hf", "LLaVA-OneVision"),
    ("llava-v1.6-mistral-7b-hf", "LLaVA-NeXT"),
)


def metrics_from(section: dict) -> tuple[float, float, float]:
    m = section["metrics"]
    names = m["positions"]
    return (m["per_position"][names[0]]["accuracy"],
            m["per_position"][names[-1]]["accuracy"],
            m["flip"][-1])


def row(short: str, dataset: str, data: dict) -> str:
    raw = metrics_from(data["raw"])
    grey = metrics_from(data["grey"])
    return (f"{short} & {dataset} & {raw[0]:.3f} & {raw[1]:.3f} & {raw[2]:.3f}"
            f" & {grey[0]:.3f} & {grey[1]:.3f} & {grey[2]:.3f} \\\\")


def main() -> int:
    lines = [
        "% generated by make_grey_table.py",
        "\\begin{tabular}{llrrrrrr}",
        "\\toprule",
        "Model & Dataset & raw pre & raw suf & raw flip & grey pre & grey suf & grey flip \\\\",
        "\\midrule",
    ]
    lines.append("\\multicolumn{8}{l}{\\textit{Qwen}} \\\\")
    for _, short, files in QWEN:
        for f in files:
            data = json.loads((RESULTS / f).read_text(encoding="utf-8"))
            dataset = data["dataset"]
            label = {"aokvqa": "A-OKVQA", "eurosat": "EuroSAT"}[dataset]
            lines.append(row(short, label, data))
    lines.append("\\midrule")
    lines.append("\\multicolumn{8}{l}{\\textit{Non-Qwen}} \\\\")
    for slug, short in NONQWEN:
        for ds, label in (("aokvqa", "A-OKVQA"), ("eurosat", "EuroSAT")):
            data = json.loads((RESULTS / f"{slug}_{ds}_grey.json").read_text(encoding="utf-8"))
            lines.append(row(short, label, data))
    lines.extend(["\\bottomrule", "\\end{tabular}"])
    TABLES.mkdir(parents=True, exist_ok=True)
    (TABLES / "grey.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {TABLES / 'grey.tex'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
