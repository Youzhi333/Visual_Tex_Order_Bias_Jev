"""Four-position statistics on the full evaluation sets.

    python research2visualtexorder/full_positions.py

The full-set tables report prefix and suffix only; this adds the intermediate
placements from the same *_full.json files. No new runs.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from scipy.stats import binomtest


def mcnemar(a, b):
    a = np.asarray(a, dtype=bool)
    b = np.asarray(b, dtype=bool)
    n01, n10 = int(np.sum(~a & b)), int(np.sum(a & ~b))
    if n01 + n10 == 0:
        return 1.0
    return float(binomtest(n01, n01 + n10, 0.5).pvalue)

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results" / "2026-11-12"


def main() -> int:
    rows = []
    for path in sorted(RESULTS.glob("*_full.json")):
        if "label_perm" in path.name or "analysis" in path.name:
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        metrics = data["raw"]["metrics"]
        names = metrics["positions"]
        truth = [it["answer"] for it in data["items"]]
        correct = [np.asarray([p == t for p, t in zip(
            data["raw"]["preds"][n], truth)], dtype=float) for n in names]
        rows.append({
            "model": data["model"], "dataset": data["dataset"],
            "flip": [float(x) for x in metrics["flip"]],
            "accuracy": [float(metrics["per_position"][n]["accuracy"]) for n in names],
            "mcnemar_vs_prefix": [mcnemar(correct[0], correct[i]) for i in range(1, 4)],
        })
    lines = [
        "% generated by full_positions.py from *_full.json",
        "\\begin{tabular}{lrrrrrr}",
        "\\toprule",
        "Family & cells & $F_{\\mathrm{mid}}$ & $F_{\\mathrm{ques}}$ & $F_{\\mathrm{suf}}$ "
        "& acc prefix & acc suffix \\\\",
        "\\midrule",
    ]
    out = {"rows": rows}
    for label, test in (("Qwen", lambda m: "Qwen" in m),
                        ("Non-Qwen", lambda m: "Qwen" not in m),
                        ("All", lambda m: True)):
        group = [r for r in rows if test(r["model"])]
        if not group:
            continue
        flip = [float(np.mean([r["flip"][i] for r in group])) for i in range(4)]
        acc = [float(np.mean([r["accuracy"][i] for r in group])) for i in range(4)]
        sig = [sum(r["mcnemar_vs_prefix"][i] < 0.05 for r in group)
               for i in range(3)]
        out[label] = {"cells": len(group), "flip": flip, "accuracy": acc,
                      "mcnemar_significant": sig}
        lines.append(f"{label} & {len(group)} & {flip[1]:.3f} & {flip[2]:.3f} & "
                     f"{flip[3]:.3f} & {acc[0]:.3f} & {acc[3]:.3f} \\\\")
        print(label, len(group), "flip", [round(x, 3) for x in flip],
              "acc", [round(x, 3) for x in acc], "McNemar sig", sig)
    lines += ["\\bottomrule", "\\end{tabular}"]
    (RESULTS / "analysis_full_positions.json").write_text(
        json.dumps(out, indent=2), encoding="utf-8")
    tex = ROOT / "paper/tables/full_positions.tex"
    tex.parent.mkdir(parents=True, exist_ok=True)
    tex.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {RESULTS / 'analysis_full_positions.json'}\nwrote {tex}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
