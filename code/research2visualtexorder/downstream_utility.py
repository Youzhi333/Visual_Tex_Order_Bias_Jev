"""Action-level proxy: selective prediction under prefix and suffix.

    python research2visualtexorder/downstream_utility.py

No downstream labels exist, so we use the readout's own confidence as a gate:
accept a decision above a threshold, otherwise abstain. Utility is +1 for a
correct accepted decision, -1 for a wrong one, 0 for abstaining. AURC is the
area under the risk-coverage curve. This is a proxy, not a deployed task.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results" / "2026-11-12"


def curve(conf, correct):
    order = np.argsort(-np.asarray(conf))
    correct = np.asarray(correct)[order]
    n = len(correct)
    coverages = np.arange(1, n + 1) / n
    risks = 1.0 - np.cumsum(correct) / np.arange(1, n + 1)
    return float(np.trapezoid(risks, coverages)), coverages, risks


def utility(conf, correct, threshold):
    conf = np.asarray(conf)
    correct = np.asarray(correct)
    accept = conf >= threshold
    if not accept.any():
        return 0.0, 0.0
    return float(correct[accept].mean() * 2.0 - 1.0), float(accept.mean())


def utility_cost(conf, correct, threshold, cost=5.0):
    conf = np.asarray(conf)
    correct = np.asarray(correct)
    accept = conf >= threshold
    if not accept.any():
        return 0.0
    gains = correct[accept].sum() - cost * (~correct[accept].astype(bool)).sum()
    return float(gains / len(correct))


def main() -> int:
    rows = []
    for path in sorted(RESULTS.glob("*_4pos.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        names = data["raw"]["metrics"]["positions"]
        truth = [it["answer"] for it in data["items"]]
        for label, idx in (("prefix", 0), ("suffix", -1)):
            name = names[idx]
            pred = data["raw"]["preds"][name]
            conf = np.asarray(data["raw"]["confs"][name] if "confs" in data["raw"]
                              else data["raw"]["confidences"][name], dtype=float)
            correct = np.asarray([a == t for a, t in zip(pred, truth)], dtype=float)
            aurc, _, _ = curve(conf, correct)
            u50, c50 = utility(conf, correct, 0.5)
            u80, c80 = utility(conf, correct, 0.8)
            rows.append({"source": path.name, "model": data["model"],
                         "dataset": data["dataset"], "position": label,
                         "accuracy": float(correct.mean()), "aurc": aurc,
                         "utility@0.5": u50, "coverage@0.5": c50,
                         "utility@0.8": u80, "coverage@0.8": c80,
                         "utility_cost5@0.5": utility_cost(conf, correct, 0.5)})
    out = {"description": "selective-prediction proxy; confidence gate",
           "rows": rows}
    (RESULTS / "analysis_downstream_utility.json").write_text(
        json.dumps(out, indent=2), encoding="utf-8")
    lines = [
        "% generated by downstream_utility.py",
        "\\begin{tabular}{lrrrrr}",
        "\\toprule",
        "Family & prefix AURC & suffix AURC & prefix $U_{.5}$/cov & "
        "suffix $U_{.5}$/cov & cost-5 pre/suf \\\\",
        "\\midrule",
    ]
    for label, test in (("Qwen", lambda m: "Qwen" in m),
                        ("Non-Qwen", lambda m: "Qwen" not in m)):
        group = [r for r in rows if test(r["model"])]
        if not group:
            continue
        p = [r for r in group if r["position"] == "prefix"]
        s = [r for r in group if r["position"] == "suffix"]
        vals = {
            "p_aurc": np.mean([r["aurc"] for r in p]),
            "s_aurc": np.mean([r["aurc"] for r in s]),
            "p_u": np.mean([r["utility@0.5"] for r in p]),
            "s_u": np.mean([r["utility@0.5"] for r in s]),
            "p_c": np.mean([r["coverage@0.5"] for r in p]),
            "s_c": np.mean([r["coverage@0.5"] for r in s]),
            "p_cost": np.mean([r["utility_cost5@0.5"] for r in p]),
            "s_cost": np.mean([r["utility_cost5@0.5"] for r in s]),
        }
        lines.append(f"{label} & {vals['p_aurc']:.3f} & {vals['s_aurc']:.3f} & "
                     f"{vals['p_u']:.3f}/{vals['p_c']:.2f} & "
                     f"{vals['s_u']:.3f}/{vals['s_c']:.2f} & "
                     f"{vals['p_cost']:.3f}/{vals['s_cost']:.3f} \\\\")
        print(label, {k: round(v, 3) for k, v in vals.items()})
    lines += ["\\bottomrule", "\\end{tabular}"]
    tex = ROOT / "paper/tables/downstream.tex"
    tex.parent.mkdir(parents=True, exist_ok=True)
    tex.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {RESULTS / 'analysis_downstream_utility.json'}\nwrote {tex}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
