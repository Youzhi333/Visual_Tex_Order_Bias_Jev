"""The complete readout table (tab:fuse).

    python research2visualtexorder/make_fuse_table.py

Writes paper/tables/fuse_table.tex with one row per readout and three column
groups (all-model, Qwen, non-Qwen), each with accuracy, flip, ECE and forwards.
Pointwise has separate prefix and suffix rows and uses only its 14
A-OKVQA/EuroSAT cells (eight Qwen, six non-Qwen).
"""
from __future__ import annotations

from pathlib import Path

from readouts import READOUTS, cell, pointwise_metrics

ROOT = Path(__file__).resolve().parent
TABLES = ROOT / "paper" / "tables"
MODELS = (
    ("Qwen", "Qwen3-VL-2B-Instruct"),
    ("Qwen", "Qwen3-VL-4B-Instruct"),
    ("Qwen", "Qwen3-VL-8B-Instruct"),
    ("Qwen", "Qwen2.5-VL-7B-Instruct"),
    ("Non-Qwen", "Idefics3-8B-Llama3"),
    ("Non-Qwen", "llava-onevision-qwen2-7b-ov-hf"),
    ("Non-Qwen", "llava-v1.6-mistral-7b-hf"),
)
DATASETS = ("aokvqa", "scienceqa", "cvbench", "eurosat", "pets", "mmmu")
KEYS = ("prefix", "pre_q", "pre_o", "suffix", "all_mean", "all_logmean",
        "ps", "p_q_o", "q_o", "p_q", "p_o", "m_m", "dof50", "dof75")
FORWARDS = {
    "prefix": 1, "pre_q": 1, "pre_o": 1, "suffix": 1,
    "all_mean": 4, "all_logmean": 4, "ps": 2,
    "p_q_o": 3, "q_o": 2, "p_q": 2, "p_o": 2, "m_m": 4,
    "dof50": 2, "dof75": 2,
}
LABELS = {key: label for label, key in READOUTS}


def mean3(values: list[tuple[float, float, float]]) -> tuple[float, float, float]:
    n = len(values)
    return (sum(v[0] for v in values) / n,
            sum(v[1] for v in values) / n,
            sum(v[2] for v in values) / n)


def main() -> int:
    cells = {(slug, ds): cell(slug, ds) for _, slug in MODELS for ds in DATASETS}
    pw = {(slug, ds): pointwise_metrics(slug, ds)
          for _, slug in MODELS for ds in DATASETS}
    pw = {k: v for k, v in pw.items() if v is not None}

    qwen = [slug for group, slug in MODELS if group == "Qwen"]
    nonqwen = [slug for group, slug in MODELS if group == "Non-Qwen"]
    groups = (
        ("All-model mean (42 cells)",
         [(slug, ds) for _, slug in MODELS for ds in DATASETS]),
        ("Qwen mean (24 cells)", [(slug, ds) for slug in qwen for ds in DATASETS]),
        ("Non-Qwen mean (18 cells)",
         [(slug, ds) for slug in nonqwen for ds in DATASETS]),
    )

    lines = [
        "% generated by make_fuse_table.py",
        "\\begin{tabular}{@{}l rrrr rrrr rrrr@{}}",
        "\\toprule",
    ]
    lines.append("& " + " & ".join(
        f"\\multicolumn{{4}}{{c}}{{\\textit{{{title}}}}}" for title, _ in groups) + " \\\\")
    lines.append("\\cmidrule(lr){2-5}\\cmidrule(lr){6-9}\\cmidrule(l){10-13}")
    lines.append("Readout & " + " & ".join(["Acc. & Flip & ECE & Fwd"] * 3) + " \\\\")
    lines.append("\\midrule")
    for key in KEYS:
        out = []
        for _, pairs in groups:
            acc, flip, ece = mean3([cells[p][key] for p in pairs])
            out.append(f"{acc:.3f} & {flip:.3f} & {ece:.3f} & {FORWARDS[key]}")
        lines.append(f"{LABELS[key]} & " + " & ".join(out) + " \\\\")
    pointwise_rows = (
        ("Pointwise (prefix)", "pre_acc", None, "pre_ece"),
        ("Pointwise (suffix)", "suf_acc", "suf_flip_within", "suf_ece"),
    )
    for label, acc_key, flip_key, ece_key in pointwise_rows:
        out = []
        for _, pairs in groups:
            vals = [pw[p] for p in pairs if p in pw]
            acc = sum(v[acc_key] for v in vals) / len(vals)
            flip = 0.0 if flip_key is None else sum(v[flip_key] for v in vals) / len(vals)
            ece = sum(v[ece_key] for v in vals) / len(vals)
            out.append(f"{acc:.3f} & {flip:.3f} & {ece:.3f} & $K$")
        lines.append(f"{label} & " + " & ".join(out) + " \\\\")
    lines.extend(["\\bottomrule", "\\end{tabular}"])

    TABLES.mkdir(parents=True, exist_ok=True)
    (TABLES / "fuse_table.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {TABLES / 'fuse_table.tex'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
