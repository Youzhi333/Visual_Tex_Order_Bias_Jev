"""Per-cell tables behind the mean tables.

    python research2visualtexorder/make_fullcell_tables.py

Writes paper/tables/{positions_full,fuse_full}.tex from the committed
_4pos.json files for all seven checkpoints. The fusion cells use the same
offline baselines as paper_stats.py. Pointwise cells come from the
_pointwise.json files and are blank where that control was not run.
"""
from __future__ import annotations

import json
from pathlib import Path

from paper_stats import read_cell
from readouts import cell as readout_cell

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results" / "2026-11-12"
TABLES = ROOT / "paper" / "tables"
GROUPS = (
    ("Qwen", (
        ("Qwen3-VL-2B-Instruct", "2B"),
        ("Qwen3-VL-4B-Instruct", "4B"),
        ("Qwen3-VL-8B-Instruct", "8B"),
        ("Qwen2.5-VL-7B-Instruct", "7B"),
    )),
    ("Non-Qwen", (
        ("Idefics3-8B-Llama3", "Idefics3-8B"),
        ("llava-onevision-qwen2-7b-ov-hf", "LLaVA-OneVision"),
        ("llava-v1.6-mistral-7b-hf", "LLaVA-NeXT"),
    )),
)
DATASETS = (("aokvqa", "A-OKVQA"), ("scienceqa", "ScienceQA"),
            ("cvbench", "CV-Bench"), ("eurosat", "EuroSAT"),
            ("pets", "Pets"), ("mmmu", "MMMU"))


def main() -> int:
    pos_rows, fuse_rows = [], []
    for gi, (group, models) in enumerate(GROUPS):
        if gi:
            pos_rows.append("\\midrule")
            fuse_rows.append("\\midrule")
        pos_rows.append(f"\\multicolumn{{17}}{{l}}{{\\textit{{{group}}}}} \\\\")
        fuse_rows.append(f"\\multicolumn{{11}}{{l}}{{\\textit{{{group}}}}} \\\\")
        for slug, short in models:
            for key, label in DATASETS:
                path = RESULTS / f"{slug}_{key}_4pos.json"
                raw = read_cell(path)
                if not raw:
                    continue
                m = json.loads(path.read_text(encoding="utf-8"))["raw"]["metrics"]
                flip, tv = m["flip"], m["tv"]
                acc = [m["per_position"][n]["accuracy"] for n in m["positions"]]
                b, bf = raw["baselines"], raw["baseline_flips"]
                rc = readout_cell(slug, key)
                pw_path = RESULTS / f"{slug}_{key}_pointwise.json"
                pw = ""
                pw_pre = pw_acc = "--"
                if pw_path.exists():
                    pd = json.loads(pw_path.read_text(encoding="utf-8"))
                else:
                    pd = {}
                if "pointwise" in pd:
                    pm = pd["pointwise"]["metrics"]
                    names = pd["positions"]
                    pw_pre = f"{pm['per_position'][names[0]]['accuracy']:.3f}"
                    pw_acc = f"{pm['per_position'][names[-1]]['accuracy']:.3f}"
                    pw = (f" & {pw_pre} & {pw_acc}"
                          f" & {pm['flip'][-1]:.3f}")
                else:
                    pw = " & -- & -- & --"
                pos_rows.append(
                    f"{short} & {label} & {flip[1]:.3f} & {flip[2]:.3f} & "
                    f"{flip[3]:.3f} & {tv[1]:.3f} & {tv[2]:.3f} & "
                    f"{tv[3]:.3f} & {acc[0]:.3f} & {acc[1]:.3f} & "
                    f"{acc[2]:.3f} & {acc[3]:.3f} & "
                    f"{rc['p_q'][0]:.3f} & {rc['dof50'][0]:.3f} & "
                    f"{rc['dof75'][0]:.3f} & {pw_pre} & {pw_acc} \\\\")
                fuse_rows.append(
                    f"{short} & {label} & {b['all_mean']:.3f} & "
                    f"{b['all_logmean']:.3f} & {b['prefix_suffix_mean']:.3f} & "
                    f"{b['dof_beta0.5']:.3f} & {b['dof_beta0.75']:.3f} & "
                    f"{bf['dof_beta0.75']:.3f}{pw} \\\\")

    pos_tex = [
        "% generated by make_fullcell_tables.py",
        "\\begin{tabular}{llrrrrrr rrrr rrrrr}",
        "\\toprule",
        "Model & Dataset & $F_{\\mathrm{mid}}$ & $F_{\\mathrm{ques}}$ & "
        "$F_{\\mathrm{suf}}$ & $T_{\\mathrm{mid}}$ & $T_{\\mathrm{ques}}$ & "
        "$T_{\\mathrm{suf}}$ & prefix & pre-Q & pre-O & suffix & P+Q & "
        "DOF 0.5 & DOF 0.75 & $P_{\\mathrm{pt}}$ pre & $P_{\\mathrm{pt}}$ suf \\\\",
        "\\midrule",
        *pos_rows,
        "\\bottomrule",
        "\\end{tabular}",
    ]
    fuse_tex = [
        "% generated by make_fullcell_tables.py",
        "\\begin{tabular}{llrrrrrrrrr}",
        "\\toprule",
        "Model & Dataset & All-mean & All-logmean & P+S mean & "
        "DOF 0.5 & DOF 0.75 & DOF 0.75 flip & "
        "$P_{\\mathrm{pt}}$ pre & $P_{\\mathrm{pt}}$ acc & "
        "$P_{\\mathrm{pt}}$ flip \\\\",
        "\\midrule",
        *fuse_rows,
        "\\bottomrule",
        "\\end{tabular}",
    ]
    TABLES.mkdir(parents=True, exist_ok=True)
    for name, lines in (("positions_full.tex", pos_tex), ("fuse_full.tex", fuse_tex)):
        (TABLES / name).write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"wrote {TABLES / name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
