"""Averaging ablations over the four image placements.

    python research2visualtexorder/make_avg_tables.py

Writes paper/tables/avg_full.tex from the committed _4pos.json files. P=prefix, Q=pre-question, O=pre-options, S=suffix.
The five variants are:
  P+Q+O  mean of prefix, pre-question and pre-options
  Q+O    mean of pre-question and pre-options
  P+Q    mean of prefix and pre-question
  P+O    mean of prefix and pre-options
  M+M    mean of the all-position mean and all-position log-mean distributions
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from paper_stats import acc_of, ece_of, logmean, pred_of

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results" / "2026-11-12"
TABLES = ROOT / "paper" / "tables"
GROUPS = (
    ("Qwen", (
        ("Qwen3-VL-2B-Instruct", "2B"),
        ("Qwen3-VL-4B-Instruct", "4B"),
        ("Qwen3-VL-8B-Instruct", "8B"),
        ("Qwen2.5-VL-7B-Instruct", "7B"),
    )),
    ("Non-Qwen", (
        ("Idefics3-8B-Llama3", "Idefics3-8B"),
        ("llava-onevision-qwen2-7b-ov-hf", "LLaVA-OneVision"),
        ("llava-v1.6-mistral-7b-hf", "LLaVA-NeXT"),
    )),
)
DATASETS = (("aokvqa", "A-OKVQA"), ("scienceqa", "ScienceQA"),
            ("cvbench", "CV-Bench"), ("eurosat", "EuroSAT"),
            ("pets", "Pets"), ("mmmu", "MMMU"))
KEYS = ("p_q_o", "q_o", "p_q", "p_o", "m_m")
LABELS = {"p_q_o": "P+Q+O", "q_o": "Q+O", "p_q": "P+Q",
          "p_o": "P+O", "m_m": "M+M"}
FORWARDS = {"p_q_o": 3, "q_o": 2, "p_q": 2, "p_o": 2, "m_m": 4}


def variants(p: np.ndarray) -> dict[str, np.ndarray]:
    all_mean = p.mean(axis=1)
    return {
        "p_q_o": p[:, :3].mean(axis=1),
        "q_o": p[:, 1:3].mean(axis=1),
        "p_q": p[:, :2].mean(axis=1),
        "p_o": p[:, [0, 2]].mean(axis=1),
        "m_m": (all_mean + logmean(p.transpose(1, 0, 2))) / 2.0,
    }


def cell(slug: str, dataset: str) -> dict[str, tuple[float, float, float]]:
    data = json.loads((RESULTS / f"{slug}_{dataset}_4pos.json").read_text(encoding="utf-8"))
    names = data["raw"]["metrics"]["positions"]
    items = data["items"]
    truth = [it["answer"] for it in items]
    p = np.stack([np.asarray(data["raw"]["probs"][n], dtype=float) for n in names], axis=1)
    prefix_pred = pred_of(p[:, 0], items)
    out = {}
    for key, probs in variants(p).items():
        pred = pred_of(probs, items)
        correct = acc_of(probs, truth, items)
        flip = float(np.mean([a != b for a, b in zip(pred, prefix_pred)]))
        out[key] = (float(correct.mean()), flip, ece_of(probs, correct))
    return out


def main() -> int:
    full_lines = []
    for gi, (group, models) in enumerate(GROUPS):
        if gi:
            full_lines.append("\\midrule")
        full_lines.append(f"\\multicolumn{{12}}{{l}}{{\\textit{{{group}}}}} \\\\")
        for slug, short in models:
            for key, label in DATASETS:
                m = cell(slug, key)
                accs = " & ".join(f"{m[k][0]:.3f}" for k in KEYS)
                flips = " & ".join(f"{m[k][1]:.3f}" for k in KEYS)
                full_lines.append(f"{short} & {label} & {accs} & {flips} \\\\")

    full = [
        "% generated by make_avg_tables.py",
        "\\begin{tabular}{llrrrrr rrrrr}",
        "\\toprule",
        " & & \\multicolumn{5}{c}{Accuracy} & \\multicolumn{5}{c}{Flip vs prefix} \\\\",
        "\\cmidrule(lr){3-7}\\cmidrule(l){8-12}",
        "Model & Dataset & P+Q+O & Q+O & P+Q & P+O & M+M & "
        "P+Q+O & Q+O & P+Q & P+O & M+M \\\\",
        "\\midrule",
        *full_lines,
        "\\bottomrule",
        "\\end{tabular}",
    ]
    TABLES.mkdir(parents=True, exist_ok=True)
    (TABLES / "avg_full.tex").write_text("\n".join(full) + "\n", encoding="utf-8")
    print(f"wrote {TABLES / 'avg_full.tex'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
