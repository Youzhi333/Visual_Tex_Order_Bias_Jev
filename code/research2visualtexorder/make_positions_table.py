"""The complete position table (tab:positions).

    python research2visualtexorder/make_positions_table.py

Writes paper/tables/positions_table.tex: all-model, Qwen and non-Qwen panels
with identical headers. The last four columns are P+Q, dual-order fusion at
beta=0.5 and 0.75, and pointwise suffix accuracy.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from readouts import cell as readout_cell

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results" / "2026-11-12"
TABLES = ROOT / "paper" / "tables"
MODELS = (
    ("Qwen", "Qwen3-VL-2B-Instruct"),
    ("Qwen", "Qwen3-VL-4B-Instruct"),
    ("Qwen", "Qwen3-VL-8B-Instruct"),
    ("Qwen", "Qwen2.5-VL-7B-Instruct"),
    ("Non-Qwen", "Idefics3-8B-Llama3"),
    ("Non-Qwen", "llava-onevision-qwen2-7b-ov-hf"),
    ("Non-Qwen", "llava-v1.6-mistral-7b-hf"),
)
DATASETS = (("aokvqa", "A-OKVQA"), ("scienceqa", "ScienceQA"),
            ("cvbench", "CV-Bench"), ("eurosat", "EuroSAT"),
            ("pets", "Pets"), ("mmmu", "MMMU"))


def raw(slug: str, dataset: str) -> list[float]:
    data = json.loads((RESULTS / f"{slug}_{dataset}_4pos.json").read_text(encoding="utf-8"))
    m = data["raw"]["metrics"]
    acc = [m["per_position"][n]["accuracy"] for n in m["positions"]]
    return [m["flip"][1], m["flip"][2], m["flip"][3],
            m["tv"][1], m["tv"][2], m["tv"][3], *acc]


def dataset_row(models: list[str], dataset: str) -> list[float | None]:
    raw_vals = np.asarray([raw(slug, dataset) for slug in models])
    readout_vals = np.asarray([[readout_cell(slug, dataset)[k][0]
                                for k in ("p_q", "dof50", "dof75")]
                               for slug in models])
    return [*raw_vals.mean(axis=0), *readout_vals.mean(axis=0)]


def main() -> int:
    lines = [
        "% generated by make_positions_table.py",
        "\\begin{tabular}{@{}lrrrrrr rrrr rrr@{}}",
        "\\toprule",
        "& \\multicolumn{3}{c}{Flip vs prefix} & \\multicolumn{3}{c}{TV vs prefix}"
        " & \\multicolumn{4}{c}{Accuracy} & \\multicolumn{3}{c}{Readout accuracy} \\\\",
        "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}\\cmidrule(lr){8-11}\\cmidrule(l){12-14}",
        "Dataset & $F_{\\mathrm{mid}}$ & $F_{\\mathrm{ques}}$ & $F_{\\mathrm{suf}}$"
        " & $T_{\\mathrm{mid}}$ & $T_{\\mathrm{ques}}$ & $T_{\\mathrm{suf}}$"
        " & prefix & pre-Q & pre-O & suffix & P+Q & DOF 0.5 & DOF 0.75 \\\\",
        "\\midrule",
    ]
    for gi, (group, title) in enumerate((
            ("All", "All-model mean (42 cells)"),
            ("Qwen", "Qwen mean (24 cells)"),
            ("Non-Qwen", "Non-Qwen mean (18 cells)"))):
        models = [slug for g, slug in MODELS if group == "All" or g == group]
        if gi:
            lines.append("\\midrule")
        lines.append(f"\\multicolumn{{14}}{{l}}{{\\textit{{{title}}}}}\\\\")
        rows = []
        for ds, label in DATASETS:
            vals = dataset_row(models, ds)
            rows.append(vals)
            cells = " & ".join("--" if v is None else f"{v:.3f}" for v in vals)
            lines.append(f"{label} & {cells} \\\\")
        # Mean row: dataset means for the metrics.
        mean_vals = [float(np.mean([r[col] for r in rows])) for col in range(13)]
        cells = " & ".join("--" if v is None else f"{v:.3f}" for v in mean_vals)
        lines.append(f"Mean & {cells} \\\\")
    lines.extend(["\\bottomrule", "\\end{tabular}"])
    (TABLES / "positions_table.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {TABLES / 'positions_table.tex'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
