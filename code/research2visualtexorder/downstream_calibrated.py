"""Calibration-corrected selective-prediction proxy.

    python research2visualtexorder/downstream_calibrated.py

Temperature-scales each position on even items, evaluates selective utility on
odd items. This tests whether the suffix utility drop is a calibration artifact.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results" / "2026-11-12"
GRID = np.linspace(0.5, 3.0, 26)


def softmax(z):
    z = z - z.max(axis=1, keepdims=True)
    p = np.exp(z)
    return p / p.sum(axis=1, keepdims=True)


def fit_temperature(probs, gold):
    logits = np.log(np.clip(probs, 1e-12, None))
    best, best_t = 1e9, 1.0
    for t in GRID:
        p = softmax(logits / t)
        nll = -np.log(np.clip(p[np.arange(len(gold)), gold], 1e-12, None)).mean()
        if nll < best:
            best, best_t = nll, float(t)
    return best_t


def utility(conf, correct, threshold=0.5):
    accept = conf >= threshold
    if not accept.any():
        return 0.0, 0.0
    return float(correct[accept].mean() * 2 - 1), float(accept.mean())


def main() -> int:
    rows = []
    for path in sorted(RESULTS.glob("*_4pos.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        names = data["raw"]["metrics"]["positions"]
        items = data["items"]
        truth = [it["answer"] for it in items]
        for label, idx in (("prefix", 0), ("suffix", -1)):
            name = names[idx]
            probs = np.asarray(data["raw"]["probs"][name], dtype=float)
            gold = np.asarray([it["options"].index(it["answer"]) for it in items])
            correct = np.asarray([it["options"][int(j)] == it["answer"]
                                  for j, it in zip(probs.argmax(1), items)], dtype=float)
            cal = np.arange(len(items)) % 2 == 0
            ev = ~cal
            t = fit_temperature(probs[cal], gold[cal])
            calib = softmax(np.log(np.clip(probs, 1e-12, None)) / t)
            c_raw, cov_raw = utility(probs[ev].max(1), correct[ev])
            c_cal, cov_cal = utility(calib[ev].max(1), correct[ev])
            rows.append({"model": data["model"], "dataset": data["dataset"],
                         "position": label, "temperature": t,
                         "utility_raw": c_raw, "coverage_raw": cov_raw,
                         "utility_calibrated": c_cal, "coverage_calibrated": cov_cal})
    out = {"rows": rows}
    (RESULTS / "analysis_downstream_calibrated.json").write_text(
        json.dumps(out, indent=2), encoding="utf-8")
    lines = [
        "% generated by downstream_calibrated.py",
        "\\begin{tabular}{lrrrr}",
        "\\toprule",
        "Family & prefix raw/cal & suffix raw/cal & coverage pre/suf \\\\",
        "\\midrule",
    ]
    for label, test in (("Qwen", lambda m: "Qwen" in m),
                        ("Non-Qwen", lambda m: "Qwen" not in m)):
        group = [r for r in rows if test(r["model"])]
        p = [r for r in group if r["position"] == "prefix"]
        s = [r for r in group if r["position"] == "suffix"]
        vals = {k: float(np.mean([r[k] for r in p if r["position"] == "prefix"]))
                for k in ("utility_raw", "utility_calibrated")}
        svals = {k: float(np.mean([r[k] for r in s])) for k in
                 ("utility_raw", "utility_calibrated")}
        covp = float(np.mean([r["coverage_raw"] for r in p]))
        covs = float(np.mean([r["coverage_raw"] for r in s]))
        lines.append(f"{label} & {vals['utility_raw']:.3f}/{vals['utility_calibrated']:.3f} & "
                     f"{svals['utility_raw']:.3f}/{svals['utility_calibrated']:.3f} & "
                     f"{covp:.2f}/{covs:.2f} \\\\")
        print(label, "prefix", vals, "suffix", svals, "coverage", covp, covs)
    lines += ["\\bottomrule", "\\end{tabular}"]
    tex = ROOT / "paper/tables/downstream_calibrated.tex"
    tex.parent.mkdir(parents=True, exist_ok=True)
    tex.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {RESULTS / 'analysis_downstream_calibrated.json'}\nwrote {tex}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
